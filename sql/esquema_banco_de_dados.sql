-- ============================================================
-- SISTEMA DE GESTAO DE VISITAS E AGENDAMENTOS
-- Supabase + PostgreSQL + Supabase Auth + RLS
-- ============================================================
--
-- MODELO DE ACESSO:
--
-- USER
--   - consulta seu proprio cadastro
--   - consulta funcoes, locais e tarefas ativos
--   - consulta seus proprios agendamentos
--   - cria agendamentos somente para si
--   - edita somente seus proprios agendamentos
--
-- ADM
--   - consulta todos os usuarios
--   - altera dados complementares dos usuarios
--   - consulta todos os agendamentos
--   - cria/edita agendamentos
--   - gerencia funcoes, locais e tarefas
--
-- IMPORTANTE:
-- Nunca utilizar SERVICE_ROLE no frontend.
-- ============================================================


-- ============================================================
-- 0. EXTENSAO
-- ============================================================

create extension if not exists pgcrypto;


-- ============================================================
-- 1. TABELA FUNCOES
-- ============================================================

create table if not exists public.funcoes (
    id bigint generated by default as identity primary key,
    nome text not null,
    ativo boolean not null default true,

    constraint funcoes_nome_obrigatorio
        check (length(trim(nome)) > 0),

    constraint funcoes_nome_unique
        unique (nome)
);


-- ============================================================
-- 2. TABELA USUARIOS
-- ============================================================

create table if not exists public.usuarios (
    id uuid primary key
        references auth.users(id)
        on delete cascade,

    nome text not null,
    email text not null,
    escopo text not null default 'user',
    funcao_id bigint
        references public.funcoes(id)
        on update cascade
        on delete set null,

    ativo boolean not null default true,
    created_at timestamptz not null default now(),

    constraint usuarios_nome_obrigatorio
        check (length(trim(nome)) > 0),

    constraint usuarios_email_obrigatorio
        check (length(trim(email)) > 0),

    constraint usuarios_escopo_check
        check (escopo in ('adm', 'user')),

    constraint usuarios_email_unique
        unique (email)
);


-- ============================================================
-- 3. TABELA LOCAIS
-- ============================================================

create table if not exists public.locais (
    id bigint generated by default as identity primary key,

    nome text not null,
    cidade text not null,
    ativo boolean not null default true,

    constraint locais_nome_obrigatorio
        check (length(trim(nome)) > 0),

    constraint locais_cidade_obrigatoria
        check (length(trim(cidade)) > 0),

    constraint locais_nome_cidade_unique
        unique (nome, cidade)
);


-- ============================================================
-- 4. TABELA TAREFAS
-- ============================================================

create table if not exists public.tarefas (
    id bigint generated by default as identity primary key,

    nome text not null,
    descricao text,
    ativo boolean not null default true,

    constraint tarefas_nome_obrigatorio
        check (length(trim(nome)) > 0),

    constraint tarefas_nome_unique
        unique (nome)
);


-- ============================================================
-- 5. TABELA AGENDAMENTOS
-- ============================================================

create table if not exists public.agendamentos (
    id bigint generated by default as identity primary key,

    usuario_id uuid not null
        references public.usuarios(id)
        on update cascade
        on delete restrict,

    local_id bigint not null
        references public.locais(id)
        on update cascade
        on delete restrict,

    tarefa_id bigint not null
        references public.tarefas(id)
        on update cascade
        on delete restrict,

    data date not null,

    periodo text not null,

    status text not null default 'planejado',

    objetivo text,

    resumo text,

    created_at timestamptz not null default now(),

    updated_at timestamptz not null default now(),

    constraint agendamentos_periodo_check
        check (
            periodo in (
                'manha',
                'tarde',
                'noite'
            )
        ),

    constraint agendamentos_status_check
        check (
            status in (
                'planejado',
                'concluido'
            )
        ),

    -- Uma visita concluida obrigatoriamente precisa de resumo.
    constraint agendamentos_resumo_concluido_check
        check (
            status <> 'concluido'
            or nullif(trim(resumo), '') is not null
        )
);


