-- ============================================================
-- 11. TRIGGER DE PROTECAO DE CAMPOS ADMINISTRATIVOS
-- ============================================================
--
-- Um usuario comum pode atualizar seu proprio registro (por
-- exemplo, se um dia o sistema permitir editar preferencias),
-- mas jamais pode alterar escopo, funcao ou o proprio status
-- de ativo/inativo. Apenas o ADM pode alterar esses campos.
-- Isso e reforcado aqui via trigger, e nao apenas via RLS,
-- pois RLS nao restringe colunas individualmente.
-- ============================================================

create or replace function public.usuarios_protege_campos_admin()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    if not public.usuario_e_adm() then
        new.escopo := old.escopo;
        new.funcao_id := old.funcao_id;
        new.ativo := old.ativo;
    end if;
    return new;
end;
$$;

drop trigger if exists trg_usuarios_protege_campos_admin
on public.usuarios;

create trigger trg_usuarios_protege_campos_admin
before update on public.usuarios
for each row
execute function public.usuarios_protege_campos_admin();


