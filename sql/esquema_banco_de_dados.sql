-- 19. TRIGGER: AUTO-CRIAR public.usuarios AO CRIAR NO AUTH
-- ============================================================
-- Quando um usuario e criado em Authentication > Users, este
-- trigger insere automaticamente a linha correspondente em
-- public.usuarios, reaproveitando o UUID do Auth.
--
-- O nome inicial vem de raw_user_meta_data->>'nome' (se for
-- informado no cadastro) ou do prefixo do e-mail.
-- ============================================================

create or replace function public.criar_usuario_apos_signup()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.usuarios (id, nome, email)
    values (
        new.id,
        coalesce(
            nullif(trim(new.raw_user_meta_data->>'nome'), ''),
            split_part(new.email, '@', 1)
        ),
        new.email
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists trg_on_auth_user_created on auth.users;

create trigger trg_on_auth_user_created
after insert on auth.users
for each row
execute function public.criar_usuario_apos_signup();

