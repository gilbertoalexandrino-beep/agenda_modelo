-- ============================================================
-- 8. FUNCOES AUXILIARES DE SEGURANCA
-- ============================================================
--
-- Precisamos consultar o perfil do usuario dentro das policies.
-- Usamos SECURITY DEFINER para evitar recursao das policies
-- da propria tabela usuarios.
--
-- ============================================================

create or replace function public.usuario_e_adm()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.usuarios u
        where u.id = (select auth.uid())
          and u.ativo = true
          and u.escopo = 'adm'
    );
$$;

create or replace function public.usuario_esta_ativo()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.usuarios u
        where u.id = (select auth.uid())
          and u.ativo = true
    );
$$;

revoke all on function public.usuario_e_adm() from public;
revoke all on function public.usuario_esta_ativo() from public;

grant execute on function public.usuario_e_adm() to authenticated;
grant execute on function public.usuario_esta_ativo() to authenticated;


